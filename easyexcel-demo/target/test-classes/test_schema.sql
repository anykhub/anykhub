CREATE TABLE IF NOT EXISTS MILITARY_STANDARD (
    MS_ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    MS_CODE VARCHAR(50) NOT NULL,
    MS_NAME VARCHAR(100) NOT NULL,
    MS_CATEGORY VARCHAR(50),
    MS_VERSION VARCHAR(20),
    DESCRIPTION VARCHAR(500),
    FILE_URL VARCHAR(200),
    STATUS CHAR(1) DEFAULT '0',
    DEL_FLAG CHAR(1) DEFAULT '0',
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    REMARK VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS TAG (
    TAG_ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    TAG_CODE VARCHAR(50) NOT NULL,
    TAG_NAME VARCHAR(100) NOT NULL,
    TAG_COLOR VARCHAR(20),
    TAG_TYPE VARCHAR(20),
    TAG_ORDER INT DEFAULT 0,
    STATUS CHAR(1) DEFAULT '0',
    DEL_FLAG CHAR(1) DEFAULT '0',
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    REMARK VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS FACILITY_TAB (
    TAB_ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    TAB_CODE VARCHAR(50) NOT NULL,
    TAB_NAME VARCHAR(100) NOT NULL,
    TAB_ICON VARCHAR(100),
    TAB_ORDER INT DEFAULT 0,
    STATUS CHAR(1) DEFAULT '0',
    DEL_FLAG CHAR(1) DEFAULT '0',
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    REMARK VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS FACILITY (
    FACILITY_ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    FACILITY_CODE VARCHAR(50) NOT NULL,
    FACILITY_NAME VARCHAR(100) NOT NULL,
    PARENT_FACILITY_ID BIGINT,
    TAB_ID BIGINT,
    COUNTRY_CODE VARCHAR(10),
    FACILITY_TYPE VARCHAR(20),
    LOCATION VARCHAR(200),
    LATITUDE DECIMAL(10, 6),
    LONGITUDE DECIMAL(10, 6),
    AREA DECIMAL(10, 2),
    CAPACITY INT,
    DESCRIPTION VARCHAR(500),
    STATUS CHAR(1) DEFAULT '0',
    DEL_FLAG CHAR(1) DEFAULT '0',
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    REMARK VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS FACILITY_MILITARY_STANDARD (
    ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    FACILITY_ID BIGINT NOT NULL,
    MS_ID BIGINT NOT NULL,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS FACILITY_TAG (
    ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    FACILITY_ID BIGINT NOT NULL,
    TAG_ID BIGINT NOT NULL,
    CREATE_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- SYS_USER table
CREATE TABLE IF NOT EXISTS SYS_USER (
    USER_ID BIGINT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    DEPT_ID BIGINT,
    USER_NAME VARCHAR(64),
    NICK_NAME VARCHAR(64),
    USER_TYPE VARCHAR(2),
    EMAIL VARCHAR(100),
    PHONENUMBER VARCHAR(20),
    SEX CHAR(1),
    AVATAR VARCHAR(200),
    PASSWORD VARCHAR(100),
    STATUS CHAR(1) DEFAULT '0',
    DEL_FLAG CHAR(1) DEFAULT '0',
    LOGIN_IP VARCHAR(50),
    LOGIN_DATE TIMESTAMP,
    CREATE_BY VARCHAR(64) DEFAULT '',
    CREATE_TIME TIMESTAMP,
    UPDATE_BY VARCHAR(64) DEFAULT '',
    UPDATE_TIME TIMESTAMP,
    REMARK VARCHAR(500)
);
